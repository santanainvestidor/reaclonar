/** Converte o símbolo do TradingView no mercado e no símbolo da API da Binance. */
export const ativo = (tv) => {
  const futuro = tv.endsWith(".P");
  const base = futuro ? tv.slice(0, -2) : tv;
  // DOGEUSD.P é margem em moeda; usamos o perpétuo DOGEUSDT, que segue o mesmo preço.
  const api = base.endsWith("USDT") ? base : base.replace(/USD$/, "USDT");
  return {
    tv,
    api,
    futuro,
    nome: base.replace(/USDT?$/, "") + (futuro ? " perp" : " spot"),
  };
};
